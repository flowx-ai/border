"""Tests for `language_id`.

**Every sentence here was written by hand and none of it is in the profile corpus.**
That is the point rather than a detail. The profiles are built by
`border_train.build_language_profiles` from ten task corpora, almost all generated by
one model, so scoring the detector on a held-out slice of that corpus would measure
whether the profile matches its own generator. It would pass and mean nothing, which
is the failure this project has recorded eight times.

So the fixtures below are ordinary administrative sentences in all 26 languages, written
for this file. If the detector ever stops passing them, the profile has drifted from the
languages rather than from the corpus.
"""

