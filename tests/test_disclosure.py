"""Tests for the disclosure detector.

Two things are being pinned here.

**Both directions are reported.** `disclosure_missing` when nothing matched and
`disclosure_present` when something did. The positive is the load-bearing one: an
auditor asking "did the assistant disclose itself?" must be able to read the answer out
of the record, not infer it from an absence, because an absence is also what a detector
that never ran produces.

**Word boundaries.** A substring search for "ai" matches "said", "again" and "email". A
regression there turns this detector into a no-op that reports success on every output,
which is the worst available failure, so it has its own tests.

All 26 languages are exercised, because a phrasings file with an untested language is a
phrasings file with a typo in it.
"""

from __future__ import annotations

import pytest

from flowx_border.detectors.base import Context, DetectorConfig
from flowx_border.detectors.disclosure import (
    DisclosureDataError,
    DisclosureDetector,
    load_phrasings,
    normalise,
    unreviewed_languages,
)
from flowx_border.types import Finding

DETECTOR = DisclosureDetector()
CFG = DetectorConfig(on_fail="flag")
CTX = Context()


def run(text: str, cfg: DetectorConfig = CFG) -> list[Finding]:
    return DETECTOR.run(text, cfg, CTX)


def labels(text: str, cfg: DetectorConfig = CFG) -> list[str]:
    return [finding.label for finding in run(text, cfg)]


# ------------------------------------------------------------------ the two findings


def test_a_plain_answer_with_no_disclosure_is_reported_missing() -> None:
    # This is the phase 2 definition of done.
    assert labels("Your balance is 412 EUR as of this morning.") == [
        "disclosure_missing"
    ]


def test_an_answer_carrying_a_disclosure_is_reported_present() -> None:
    assert labels("This response was generated by AI. Your balance is 412 EUR.") == [
        "disclosure_present"
    ]


def test_the_two_findings_are_mutually_exclusive() -> None:
    for text in ("no disclosure at all here", "I am an AI assistant."):
        assert len(labels(text)) == 1, text


def test_a_missing_disclosure_takes_its_action_from_the_policy() -> None:
    assert run("nothing here", DetectorConfig(on_fail="block"))[0].action == "block"
    assert run("nothing here", DetectorConfig(on_fail="rewrite"))[0].action == "rewrite"


def test_a_present_disclosure_is_always_logged_and_never_the_policy_action() -> None:
    # on_fail describes what to do about a missing disclosure. Applying it to a present
    # one would block outputs for complying, which is the opposite of the intent.
    finding = run("Generated by AI.", DetectorConfig(on_fail="block"))[0]
    assert finding.action == "log"


def test_a_present_disclosure_does_not_change_the_verdict() -> None:
    # `log` maps to `allow` in the engine, so recording the positive is free.
    from flowx_border.engine import run_scan
    from flowx_border.policy import Policy

    policy = Policy(
        policy_id="t",
        version=1,
        fail_mode=dict.fromkeys(("T0", "T1", "T2", "T3"), "open"),
        detectors={},
    )
    decision = run_scan(
        "Generated by AI. All good.", "output", policy, None, {"disclosure": DETECTOR}
    )
    assert decision.verdict == "allow"
    assert [f.label for f in decision.evidence.finding_summary] == [
        "disclosure_present"
    ]


def test_neither_finding_carries_a_span() -> None:
    # Missing: there is no offset for a thing that is not there, and pointing at the end
    # would imply that is where it belongs, which is not this detector's call. Present:
    # the offset would index the normalised text, not the caller's string.
    for text in ("nothing here", "Generated by AI."):
        assert run(text)[0].span is None


# --------------------------------------------------------------------- word boundaries


@pytest.mark.parametrize(
    "text",
    [
        "He said the balance was wrong.",
        "Please try again later.",
        "Send it to my email address.",
        "The claim was paid in Dubai last year.",
        "Your certificate has been mailed.",
        "Retrieved from the domain registrar.",
    ],
)
def test_a_word_merely_containing_ai_is_not_a_disclosure(text: str) -> None:
    # The regression that would make this detector useless while looking like it passes.
    assert labels(text) == ["disclosure_missing"], text


def test_a_hyphenated_disclosure_still_matches() -> None:
    assert labels("This is an AI-generated summary.") == ["disclosure_present"]


def test_matching_ignores_case() -> None:
    for text in ("GENERATED BY AI", "generated by ai", "Generated By Ai"):
        assert labels(f"{text}. Your balance is fine.") == ["disclosure_present"], text


def test_matching_survives_collapsed_whitespace() -> None:
    assert labels("generated    by\n\tai, see below") == ["disclosure_present"]


def test_matching_survives_a_decomposed_diacritic() -> None:
    # The same Romanian word arrives precomposed or decomposed depending on the platform
    # that produced it, and two spellings of one word must not be two results.
    import unicodedata

    text = "Acest răspuns a fost generat automat."
    assert labels(text) == ["disclosure_present"]
    assert labels(unicodedata.normalize("NFD", text)) == ["disclosure_present"]


