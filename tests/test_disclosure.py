# --------------------------------------------------------------------------- options


def test_a_policy_can_restrict_the_accepted_languages() -> None:
    # A product answering only in Romanian does not want an English phrase in its output
    # to count as its disclosure.
    romanian_only = DetectorConfig(options={"languages": ["ro"]})
    assert labels("This was generated by AI.", romanian_only) == ["disclosure_missing"]
    assert labels("Generat automat de AI.", romanian_only) == ["disclosure_present"]


def test_restricting_to_an_unknown_language_raises_rather_than_checking_nothing() -> (
    None
):
    with pytest.raises(DisclosureDataError, match="no phrasings"):
        DETECTOR.run("x", DetectorConfig(options={"languages": ["xx"]}), CTX)


def test_a_policy_can_add_house_wording() -> None:
    cfg = DetectorConfig(options={"extra_phrasings": ["produced by our virtual agent"]})
    assert labels("Produced by our virtual agent.", cfg) == ["disclosure_present"]
    assert labels("Produced by our virtual agent.") == ["disclosure_missing"]


def test_extra_wording_is_matched_on_boundaries_too() -> None:
    cfg = DetectorConfig(options={"extra_phrasings": ["bot"]})
    assert labels("Bot.", cfg) == ["disclosure_present"]
    assert labels("I rebooted the router.", cfg) == ["disclosure_missing"]


def test_a_short_output_can_be_exempted_but_only_explicitly() -> None:
    assert labels("Yes.") == ["disclosure_missing"]
    assert labels("Yes.", DetectorConfig(options={"min_chars": 20})) == []


def test_the_default_checks_every_length() -> None:
    # A silent length exemption is how a disclosure requirement quietly stops applying.
    assert DetectorConfig().options.get("min_chars") is None
    assert labels("Ok") == ["disclosure_missing"]


# --------------------------------------------------------------------------- plumbing


def test_normalise_collapses_and_casefolds() -> None:
    assert normalise("  Generated   BY\n AI  ") == "generated by ai"


def test_an_empty_output_is_a_missing_disclosure_not_an_error() -> None:
    assert labels("") == ["disclosure_missing"]


def test_the_detector_matches_the_catalogue() -> None:
    from flowx_border.detectors.catalogue import CATALOGUE

    spec = CATALOGUE["disclosure"]
    assert (DETECTOR.id, DETECTOR.tier) == ("disclosure", spec.tier)
    assert DETECTOR.sides == spec.sides


def test_warm_is_idempotent() -> None:
    DETECTOR.warm()
    DETECTOR.warm()
    assert labels("Generated by AI.") == ["disclosure_present"]


def test_findings_never_carry_the_output_text() -> None:
    for text in ("Generated by AI, balance 412 EUR.", "balance 412 EUR"):
        for finding in run(text):
            assert "412" not in finding.model_dump_json()
